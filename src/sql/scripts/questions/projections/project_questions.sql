                                legislature                 = EXCLUDED.legislature,
                                numero                      = EXCLUDED.numero,
                                acteur_uid                  = EXCLUDED.acteur_uid,
                                mandat_uid                  = EXCLUDED.mandat_uid,
                                groupe_uid                  = EXCLUDED.groupe_uid,
                                groupe_abrege               = EXCLUDED.groupe_abrege,
