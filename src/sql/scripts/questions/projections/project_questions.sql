       data ->> 'type_question',
       (data ->> 'legislature')::integer,
       (data ->> 'numero')::integer,
       data ->> 'acteur_uid',
       data ->> 'mandat_uid',
       data ->> 'groupe_uid',
       data ->> 'groupe_abrege',
       data ->> 'rubrique',
       data ->> 'tete_analyse',
       data ->> 'libelle_analyse',
       data ->> 'ministere_uid',
