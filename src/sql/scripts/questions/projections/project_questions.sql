       data ->> 'texte_question',
       (data ->> 'date_reponse')::date,
       data ->> 'type_jo_reponse',
       data ->> 'page_jo_reponse',
       data ->> 'texte_reponse',
       data ->> 'code_cloture',
       data ->> 'libelle_cloture',
