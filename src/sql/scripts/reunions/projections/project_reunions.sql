INSERT INTO reunions_snapshot (uid, type_reunion, legislature, organe_uid, demandeur_acteur_uid,
                               demandeur_organe_uid, etat, date_debut, date_fin,
                               session_ref, compte_rendu_ref, lieu_ref, lieu_libelle, format_reunion,
                               sous_type_reunion, visio_conference, captation_video, ouverture_presse,
                               est_reunion_internationale, date_seance, id_jo, num_seance_jo, quantieme,
                               resume_odj, convocation_odj, row_hash, legislature_snapshot)
SELECT data ->> 'uid',
       data ->> 'type_reunion',
       (data ->> 'legislature')::integer,
       data ->> 'organe_uid',
       data ->> 'demandeur_acteur_uid',
       data ->> 'demandeur_organe_uid',
       data ->> 'etat',
       (data ->> 'date_debut')::timestamptz,
       (data ->> 'date_fin')::timestamptz,
       data ->> 'session_ref',
       data ->> 'compte_rendu_ref',
       data ->> 'lieu_ref',
       data ->> 'lieu_libelle',
       data ->> 'format_reunion',
       data ->> 'sous_type_reunion',
       (data ->> 'visio_conference')::boolean,
       (data ->> 'captation_video')::boolean,
       (data ->> 'ouverture_presse')::boolean,
       (data ->> 'est_reunion_internationale')::boolean,
       (data ->> 'date_seance')::date,
       data ->> 'id_jo',
       (data ->> 'num_seance_jo')::integer,
       data ->> 'quantieme',
       data ->> 'resume_odj',
       data ->> 'convocation_odj',
       data ->> 'row_hash',
       (data ->> 'legislature_snapshot')::integer
FROM reunions_raw
ON CONFLICT (uid) DO UPDATE SET type_reunion               = EXCLUDED.type_reunion,
                                legislature                = EXCLUDED.legislature,
                                organe_uid                 = EXCLUDED.organe_uid,
                                demandeur_acteur_uid       = EXCLUDED.demandeur_acteur_uid,
                                demandeur_organe_uid       = EXCLUDED.demandeur_organe_uid,
                                etat                       = EXCLUDED.etat,
                                date_debut                 = EXCLUDED.date_debut,
                                date_fin                   = EXCLUDED.date_fin,
                                session_ref                = EXCLUDED.session_ref,
                                compte_rendu_ref           = EXCLUDED.compte_rendu_ref,
                                lieu_ref                   = EXCLUDED.lieu_ref,
                                lieu_libelle               = EXCLUDED.lieu_libelle,
                                format_reunion             = EXCLUDED.format_reunion,
                                sous_type_reunion          = EXCLUDED.sous_type_reunion,
                                visio_conference           = EXCLUDED.visio_conference,
                                captation_video            = EXCLUDED.captation_video,
                                ouverture_presse           = EXCLUDED.ouverture_presse,
                                est_reunion_internationale = EXCLUDED.est_reunion_internationale,
                                date_seance                = EXCLUDED.date_seance,
                                id_jo                      = EXCLUDED.id_jo,
                                num_seance_jo              = EXCLUDED.num_seance_jo,
                                quantieme                  = EXCLUDED.quantieme,
                                resume_odj                 = EXCLUDED.resume_odj,
                                convocation_odj            = EXCLUDED.convocation_odj,
                                row_hash                   = EXCLUDED.row_hash,
                                legislature_snapshot       = EXCLUDED.legislature_snapshot
WHERE reunions_snapshot.row_hash != EXCLUDED.row_hash;
