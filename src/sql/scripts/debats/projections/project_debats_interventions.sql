INSERT INTO debats_interventions_snapshot (id, compte_rendu_uid, point_id, ordre, acteur_uid, mandat_uid, role_debat,
                                           code_grammaire, code_style, type_debat, orateurs_libelle, texte, stime,
                                           bibard, article, amendement, sous_amendement, amendement_uid, decision,
                                           row_hash, legislature_snapshot)
SELECT data ->> 'id',
       data ->> 'compte_rendu_uid',
       data ->> 'point_id',
       (data ->> 'ordre')::integer,
       data ->> 'acteur_uid',
       data ->> 'mandat_uid',
       data ->> 'role_debat',
       data ->> 'code_grammaire',
       data ->> 'code_style',
       data ->> 'type_debat',
       data ->> 'orateurs_libelle',
       data ->> 'texte',
       (data ->> 'stime')::numeric,
       data ->> 'bibard',
       data ->> 'article',
       data ->> 'amendement',
       data ->> 'sous_amendement',
       data ->> 'amendement_uid',
       data ->> 'decision',
       data ->> 'row_hash',
       (data ->> 'legislature_snapshot')::integer
FROM debats_interventions_raw
ON CONFLICT (id) DO UPDATE SET compte_rendu_uid     = EXCLUDED.compte_rendu_uid,
                               point_id             = EXCLUDED.point_id,
                               ordre                = EXCLUDED.ordre,
                               acteur_uid           = EXCLUDED.acteur_uid,
                               mandat_uid           = EXCLUDED.mandat_uid,
                               role_debat           = EXCLUDED.role_debat,
                               code_grammaire       = EXCLUDED.code_grammaire,
                               code_style           = EXCLUDED.code_style,
                               type_debat           = EXCLUDED.type_debat,
                               orateurs_libelle     = EXCLUDED.orateurs_libelle,
                               texte                = EXCLUDED.texte,
                               stime                = EXCLUDED.stime,
                               bibard               = EXCLUDED.bibard,
                               article              = EXCLUDED.article,
                               amendement           = EXCLUDED.amendement,
                               sous_amendement      = EXCLUDED.sous_amendement,
                               amendement_uid       = EXCLUDED.amendement_uid,
                               decision             = EXCLUDED.decision,
                               row_hash             = EXCLUDED.row_hash,
                               legislature_snapshot = EXCLUDED.legislature_snapshot
WHERE debats_interventions_snapshot.row_hash != EXCLUDED.row_hash;
